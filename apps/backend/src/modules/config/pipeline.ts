/**
 * ConfigurationService apply pipeline (docs/04 §3):
 *   validate → snapshot → publish (txn) → write files → reload → verify → (rollback) → audit
 *
 * Asterisk is never left half-configured: any failure after publishing restores
 * the previous realtime rows and managed files, reloads, and records the error.
 */
import type { FastifyRequest } from 'fastify';
import type { Prisma } from '@prisma/client';
import {
  compileDialplan, validatePjsipObject, validateReferences, type PjsipObjectRef,
} from '@echelons/shared';
import { prisma } from '../../lib/prisma.js';
import { AppError } from '../../lib/errors.js';
import { SecretBox, sha256 } from '../../lib/crypto.js';
import { env } from '../../config/env.js';
import { audit } from '../audit/service.js';
import { connectorFor, type ConnectorClient } from '../connector/client.js';
import { collectDraft, compileTransports } from './collect.js';
import {
  publisherDb, readRealtimeRows, redactRows, restoreSecrets, tableColumns, toRealtimeRows, writeRealtimeRows, type RealtimeRows,
} from './publisher.js';

export const DIALPLAN_FILE = 'extensions_echelons.conf';
export const TRANSPORTS_FILE = 'pjsip_echelons_transports.conf';

export interface ApplyIssue { severity: 'error' | 'warning'; object: string; field?: string; message: string }
export interface ApplyStep { step: string; status: 'ok' | 'failed' | 'skipped'; message?: string; at: string }
export interface ApplyResult {
  versionId: string | null;
  version: number | null;
  status: 'APPLIED' | 'FAILED' | 'VALIDATION_FAILED' | 'NO_CHANGES';
  issues: ApplyIssue[];
  steps: ApplyStep[];
  restartRequired: boolean;
}

export type ProgressFn = (step: ApplyStep) => void;

interface Snapshot {
  tables: RealtimeRows;
  dialplan: string;
  transports: string;
}

const inFlight = new Set<string>();

export async function validateServerConfig(serverId: string, asteriskMajor: number, strict: boolean) {
  const draft = await collectDraft(serverId, 0);
  const issues: ApplyIssue[] = [...draft.issues];
  for (const o of [...draft.objects, ...draft.transports]) {
    for (const i of validatePjsipObject(o.type, o.name, o.params, { asteriskMajor, strictCatalog: strict })) {
      issues.push({ severity: i.severity, object: `${o.type}:${o.name}`, field: i.field, message: i.message });
    }
  }
  for (const i of validateReferences([...draft.objects, ...draft.transports])) {
    issues.push({ severity: i.severity, object: i.object, field: i.field, message: i.message });
  }
  // Endpoint context must exist in the compiled dialplan or a known (imported) context.
  const compiled = compileDialplan(draft.dialplan);
  issues.push(...compiled.issues);
  const known = new Set([
    ...compiled.contexts,
    ...(await prisma.dialplanContext.findMany({ where: { serverId, readOnly: true }, select: { name: true } })).map((c) => c.name),
  ]);
  for (const e of draft.objects.filter((o) => o.type === 'endpoint')) {
    const ctx = e.params['context'];
    if (ctx && !known.has(String(ctx))) {
      issues.push({ severity: 'warning', object: `endpoint:${e.name}`, field: 'context', message: `context "${ctx}" is not generated by the platform nor imported; make sure it exists in extensions.conf` });
    }
  }
  return { draft, compiled, issues };
}

export async function applyServerConfig(
  serverId: string,
  opts: { req?: FastifyRequest | null; summary?: string; onProgress?: ProgressFn } = {},
): Promise<ApplyResult> {
  if (inFlight.has(serverId)) throw new AppError('CONFLICT', 'A configuration apply is already running for this server');
  inFlight.add(serverId);
  const steps: ApplyStep[] = [];
  const step = (s: string, status: ApplyStep['status'], message?: string) => {
    const st = { step: s, status, message, at: new Date().toISOString() };
    steps.push(st);
    opts.onProgress?.(st);
  };
  try {
    const stale = await prisma.configurationVersion.findFirst({ where: { serverId, status: 'APPLYING', createdAt: { gt: new Date(Date.now() - 10 * 60_000) } } });
    if (stale) throw new AppError('CONFLICT', `Version v${stale.version} is still being applied`);

    const server = await prisma.asteriskServer.findUniqueOrThrow({ where: { id: serverId } });
    const connector = await connectorFor(serverId);

    // 0. Asterisk reachable + version
    const health = await connector.health();
    if (!health.ami || !health.version) throw new AppError('ASTERISK_UNAVAILABLE', 'Asterisk AMI is not connected; configuration was not applied');
    const major = health.version.major;
    if (server.versionMajor !== major || server.versionString !== health.version.raw) {
      await prisma.asteriskServer.update({ where: { id: serverId }, data: { versionMajor: major, versionString: health.version.raw, lastSeenAt: new Date() } });
    }
    step('connect', 'ok', `Asterisk ${health.version.raw}`);

    // 1. Validate
    const { draft, compiled, issues } = await validateServerConfig(serverId, major, server.strictCatalog);
    const db = publisherDb();
    const columns = await tableColumns(db, server.realtimeSchema);
    const { rows: newRows, issues: colIssues } = toRealtimeRows(draft.objects, columns);
    issues.push(...colIssues.map((i) => ({ severity: 'error' as const, object: i.object, field: i.field, message: i.message })));
    if (issues.some((i) => i.severity === 'error')) {
      step('validate', 'failed', `${issues.filter((i) => i.severity === 'error').length} error(s)`);
      await audit(opts.req ?? null, { action: 'config.apply', objectType: 'asterisk_server', objectId: serverId, objectLabel: server.name, result: 'FAILURE', error: 'validation failed', newValue: { issues } }, undefined, server.organizationId);
      return { versionId: null, version: null, status: 'VALIDATION_FAILED', issues, steps, restartRequired: server.restartRequired };
    }
    step('validate', 'ok', issues.length ? `${issues.length} warning(s)` : undefined);

    // 2. Determine changes against last applied version
    const last = await prisma.configurationVersion.findFirst({ where: { serverId, status: 'APPLIED' }, orderBy: { version: 'desc' } });
    const maxV = await prisma.configurationVersion.aggregate({ where: { serverId }, _max: { version: true } });
    const version = (maxV._max.version ?? 0) + 1;
    const dialplanText = compileDialplan({ ...draft.dialplan, version }).text;
    const transportsText = compileTransports(draft.transports, version);
    // Hash excludes version banner so "no change" is detectable.
    const dialplanHash = sha256(compiled.text.replace(/config version \d+/, ''));
    const transportsHash = sha256(transportsText.replace(/config version \d+/, ''));
    const box = new SecretBox(env().ENCRYPTION_KEY);
    const { redacted, secrets } = redactRows(newRows);
    const lastSnap = last?.snapshot as unknown as (Snapshot & { dialplanHash?: string; transportsHash?: string }) | undefined;
    const lastSecrets = last?.secretsEnc ? box.decrypt(last.secretsEnc, `cfg:${serverId}`) : '{}';
    const rowsChanged = !last || JSON.stringify(lastSnap?.tables) !== JSON.stringify(redacted) || lastSecrets !== JSON.stringify(secrets);
    const dialplanChanged = !last || last.dialplanHash !== dialplanHash;
    const transportsChanged = !last || lastSnap?.transportsHash !== transportsHash;
    if (!rowsChanged && !dialplanChanged && !transportsChanged) {
      step('diff', 'skipped', 'No changes since last applied version');
      await markPublished(serverId);
      return { versionId: last!.id, version: last!.version, status: 'NO_CHANGES', issues, steps, restartRequired: server.restartRequired };
    }

    const v = await prisma.configurationVersion.create({
      data: {
        organizationId: server.organizationId,
        serverId,
        version,
        status: 'APPLYING',
        changedById: opts.req?.auth?.sub,
        summary: opts.summary ?? null,
        snapshot: { tables: redacted, dialplan: dialplanText, transports: transportsText, dialplanHash, transportsHash } as unknown as Prisma.InputJsonValue,
        secretsEnc: box.encrypt(JSON.stringify(secrets), `cfg:${serverId}`),
        dialplanHash,
        changes: { rowsChanged, dialplanChanged, transportsChanged, warnings: issues } as unknown as Prisma.InputJsonValue,
      },
    });
    step('snapshot', 'ok', `v${version}`);

    // 3. Backup current live state (for immediate rollback)
    const previousRows = await readRealtimeRows(db, server.realtimeSchema);
    let dialplanWritten = false;
    let rowsWritten = false;

    try {
      // 4. Publish
      if (rowsChanged) {
        await writeRealtimeRows(db, server.realtimeSchema, newRows);
        rowsWritten = true;
        step('publish', 'ok', 'Sorcery realtime tables updated');
      } else step('publish', 'skipped');

      if (dialplanChanged) {
        await connector.writeFile(DIALPLAN_FILE, dialplanText);
        dialplanWritten = true;
        step('dialplan.write', 'ok');
      }
      let restartRequired = server.restartRequired;
      if (transportsChanged) {
        await connector.writeFile(TRANSPORTS_FILE, transportsText);
        restartRequired = draft.transports.length > 0 || restartRequired;
        step('transports.write', 'ok', 'Transport changes take effect after an Asterisk restart');
      }

      // 5. Reload
      if (rowsChanged) {
        await connector.reload('res_pjsip.so');
        if (draft.objects.some((o) => o.type === 'registration')) await connector.reload('res_pjsip_outbound_registration.so');
        step('reload.pjsip', 'ok');
      }
      if (dialplanChanged) {
        const out = await connector.cli('dialplan reload');
        if (!/Dialplan reloaded/i.test(out.output)) throw new Error(`dialplan reload: ${out.output.trim().slice(0, 500)}`);
        step('reload.dialplan', 'ok');
      }

      // 6. Verify
      await verify(connector, draft.objects, dialplanChanged ? compiled.contexts : []);
      step('verify', 'ok');

      await prisma.$transaction([
        prisma.configurationVersion.update({ where: { id: v.id }, data: { status: 'APPLIED', appliedAt: new Date() } }),
        prisma.asteriskServer.update({ where: { id: serverId }, data: { restartRequired } }),
      ]);
      await markPublished(serverId);
      await audit(opts.req ?? null, { action: 'config.apply', objectType: 'asterisk_server', objectId: serverId, objectLabel: `${server.name} v${version}`, result: 'SUCCESS', newValue: { version, rowsChanged, dialplanChanged, transportsChanged } }, undefined, server.organizationId);
      return { versionId: v.id, version, status: 'APPLIED', issues, steps, restartRequired };
    } catch (e) {
      const reason = (e as Error).message;
      step('apply', 'failed', reason);
      // 7. Rollback
      const rollbackErrors: string[] = [];
      if (rowsWritten) {
        await writeRealtimeRows(db, server.realtimeSchema, previousRows).catch((x) => rollbackErrors.push(`rows: ${(x as Error).message}`));
        await connector.reload('res_pjsip.so').catch((x) => rollbackErrors.push(`pjsip reload: ${(x as Error).message}`));
      }
      if (dialplanWritten) {
        await connector.restoreFile(DIALPLAN_FILE).catch((x) => rollbackErrors.push(`dialplan restore: ${(x as Error).message}`));
        await connector.cli('dialplan reload').catch((x) => rollbackErrors.push(`dialplan reload: ${(x as Error).message}`));
      }
      if (transportsChanged) await connector.restoreFile(TRANSPORTS_FILE).catch((x) => rollbackErrors.push(`transports restore: ${(x as Error).message}`));
      step('rollback', rollbackErrors.length ? 'failed' : 'ok', rollbackErrors.join('; ') || 'Previous configuration restored');
      await prisma.configurationVersion.update({ where: { id: v.id }, data: { status: 'FAILED', error: [reason, ...rollbackErrors].join('\n').slice(0, 4000) } });
      await audit(opts.req ?? null, { action: 'config.apply', objectType: 'asterisk_server', objectId: serverId, objectLabel: `${server.name} v${version}`, result: 'FAILURE', error: reason }, undefined, server.organizationId);
      return { versionId: v.id, version, status: 'FAILED', issues: [...issues, { severity: 'error', object: 'asterisk', message: reason }], steps, restartRequired: server.restartRequired };
    }
  } finally {
    inFlight.delete(serverId);
  }
}

async function verify(connector: ConnectorClient, objects: PjsipObjectRef[], contexts: string[]) {
  const endpoints = objects.filter((o) => o.type === 'endpoint').map((o) => o.name);
  const missing: string[] = [];
  for (const name of endpoints) {
    const r = await connector.ami('PJSIPShowEndpoint', { Endpoint: name });
    if (r.response !== 'Success') missing.push(name);
  }
  if (missing.length) {
    throw new Error(`Asterisk did not load endpoint(s): ${missing.slice(0, 10).join(', ')} — check the Asterisk log for sorcery/realtime errors`);
  }
  for (const ctx of contexts) {
    const out = await connector.cli(`dialplan show ${ctx}`);
    if (/There is no existence of|does not exist/i.test(out.output)) throw new Error(`dialplan context ${ctx} was not loaded`);
  }
}

async function markPublished(serverId: string) {
  const tables = ['sipEndpoint', 'sipAor', 'sipAuth', 'sipIdentify', 'sipRegistration', 'sipTransport'] as const;
  await prisma.$transaction(
    tables.map((t) =>
      // publishedHash := draftHash for every row of this server
      prisma.$executeRawUnsafe(
        `UPDATE "${mapTable(t)}" SET published_hash = draft_hash WHERE server_id = $1::uuid AND published_hash IS DISTINCT FROM draft_hash`,
        serverId,
      ),
    ),
  );
}

function mapTable(t: string): string {
  return ({ sipEndpoint: 'sip_endpoints', sipAor: 'sip_aors', sipAuth: 'sip_auths', sipIdentify: 'sip_identifies', sipRegistration: 'sip_registrations', sipTransport: 'sip_transports' } as Record<string, string>)[t]!;
}

/** Re-publish a previous version's snapshot as a new version (rollback/restore). */
export async function rollbackToVersion(versionId: string, req?: FastifyRequest | null): Promise<ApplyResult> {
  const target = await prisma.configurationVersion.findUniqueOrThrow({ where: { id: versionId } });
  if (target.status !== 'APPLIED' && target.status !== 'ROLLED_BACK') throw new AppError('CONFLICT', 'Only previously applied versions can be restored');
  const serverId = target.serverId;
  if (inFlight.has(serverId)) throw new AppError('CONFLICT', 'A configuration apply is already running for this server');
  inFlight.add(serverId);
  const steps: ApplyStep[] = [];
  const step = (s: string, status: ApplyStep['status'], message?: string) => steps.push({ step: s, status, message, at: new Date().toISOString() });
  try {
    const server = await prisma.asteriskServer.findUniqueOrThrow({ where: { id: serverId } });
    const connector = await connectorFor(serverId);
    const box = new SecretBox(env().ENCRYPTION_KEY);
    const snap = target.snapshot as unknown as Snapshot;
    const rows = restoreSecrets(snap.tables, target.secretsEnc ? JSON.parse(box.decrypt(target.secretsEnc, `cfg:${serverId}`)) : {});
    const db = publisherDb();
    const previousRows = await readRealtimeRows(db, server.realtimeSchema);
    const maxV = await prisma.configurationVersion.aggregate({ where: { serverId }, _max: { version: true } });
    const version = (maxV._max.version ?? 0) + 1;
    const v = await prisma.configurationVersion.create({
      data: {
        organizationId: server.organizationId, serverId, version, status: 'APPLYING', changedById: req?.auth?.sub,
        summary: `Rollback to v${target.version}`, snapshot: target.snapshot as Prisma.InputJsonValue, secretsEnc: target.secretsEnc,
        dialplanHash: target.dialplanHash, changes: { rollbackOf: target.version } as Prisma.InputJsonValue,
      },
    });
    try {
      await writeRealtimeRows(db, server.realtimeSchema, rows);
      await connector.writeFile(DIALPLAN_FILE, snap.dialplan);
      await connector.writeFile(TRANSPORTS_FILE, snap.transports);
      await connector.reload('res_pjsip.so');
      await connector.cli('dialplan reload');
      const endpoints = (rows['ps_endpoints'] ?? []).map((r) => ({ type: 'endpoint' as const, name: String(r['id']), params: {} }));
      await verify(connector, endpoints, []);
      step('rollback', 'ok', `Restored v${target.version} as v${version}`);
      await prisma.configurationVersion.update({ where: { id: v.id }, data: { status: 'APPLIED', appliedAt: new Date() } });
      await audit(req ?? null, { action: 'config.rollback', objectType: 'asterisk_server', objectId: serverId, objectLabel: `${server.name} v${target.version}→v${version}`, result: 'SUCCESS' }, undefined, server.organizationId);
      return { versionId: v.id, version, status: 'APPLIED', issues: [], steps, restartRequired: true };
    } catch (e) {
      const reason = (e as Error).message;
      await writeRealtimeRows(db, server.realtimeSchema, previousRows).catch(() => undefined);
      await connector.restoreFile(DIALPLAN_FILE).catch(() => undefined);
      await connector.restoreFile(TRANSPORTS_FILE).catch(() => undefined);
      await connector.reload('res_pjsip.so').catch(() => undefined);
      await connector.cli('dialplan reload').catch(() => undefined);
      await prisma.configurationVersion.update({ where: { id: v.id }, data: { status: 'FAILED', error: reason } });
      await audit(req ?? null, { action: 'config.rollback', objectType: 'asterisk_server', objectId: serverId, result: 'FAILURE', error: reason }, undefined, server.organizationId);
      step('rollback', 'failed', reason);
      return { versionId: v.id, version, status: 'FAILED', issues: [{ severity: 'error', object: 'asterisk', message: reason }], steps, restartRequired: server.restartRequired };
    }
  } finally {
    inFlight.delete(serverId);
  }
}

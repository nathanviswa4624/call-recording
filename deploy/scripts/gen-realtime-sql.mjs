// Generates deploy/asterisk/sql/asterisk_realtime.sql from the shared PJSIP catalog.
// Usage: node deploy/scripts/gen-realtime-sql.mjs [schema]   (after `pnpm --filter @echelons/shared build`)
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PJSIP_CATALOG, SORCERY_TABLES } from '../../packages/shared/dist/index.js';

const schema = process.argv[2] ?? 'asterisk';
if (!/^[a-z_][a-z0-9_]{0,62}$/.test(schema)) throw new Error('invalid schema');
const here = path.dirname(fileURLToPath(import.meta.url));
const out = [];
const q = (s) => `"${s}"`;

out.push(`-- GENERATED by deploy/scripts/gen-realtime-sql.mjs — do not edit by hand.`);
out.push(`-- Asterisk Sorcery realtime + CDR/CEL tables for schema "${schema}".`);
out.push(`-- Columns are TEXT: res_config_odbc omits NULL columns, so options unknown to an older`);
out.push(`-- Asterisk simply stay NULL; the platform's version-aware catalog prevents setting them.`);
out.push(`CREATE SCHEMA IF NOT EXISTS ${q(schema)};`, '');

for (const [type, table] of Object.entries(SORCERY_TABLES)) {
  if (!table) continue;
  const cols = [...new Set(PJSIP_CATALOG[type].map((o) => o.name))].filter((c) => c !== 'id');
  out.push(`CREATE TABLE IF NOT EXISTS ${q(schema)}.${q(table)} (`);
  out.push(`  id varchar(255) PRIMARY KEY${cols.length ? ',' : ''}`);
  out.push(cols.map((c) => `  ${q(c)} text`).join(',\n'));
  out.push(');');
  for (const c of cols) out.push(`ALTER TABLE ${q(schema)}.${q(table)} ADD COLUMN IF NOT EXISTS ${q(c)} text;`);
  out.push('');
}

// ps_contacts is written by Asterisk itself (dynamic registrations).
out.push(`CREATE TABLE IF NOT EXISTS ${q(schema)}.ps_contacts (
  id varchar(255) NOT NULL,
  uri text, expiration_time text, qualify_frequency text, outbound_proxy text, path text, user_agent text,
  qualify_timeout text, reg_server varchar(255), authenticate_qualify text, via_addr text, via_port text,
  call_id text, endpoint text, prune_on_boot text, qualify_2xx_only text,
  CONSTRAINT ps_contacts_uq UNIQUE (id, reg_server)
);
CREATE INDEX IF NOT EXISTS ps_contacts_qualify ON ${q(schema)}.ps_contacts (qualify_frequency, expiration_time);

CREATE TABLE IF NOT EXISTS ${q(schema)}.ps_systems (
  id varchar(255) PRIMARY KEY, timer_t1 text, timer_b text, compact_headers text, threadpool_initial_size text,
  threadpool_auto_increment text, threadpool_idle_timeout text, threadpool_max_size text,
  disable_tcp_switch text, follow_early_media_fork text, accept_multiple_sdp_answers text
);

-- CDR (cdr_adaptive_odbc). ech_* columns receive the CDR(ech_*) variables set by the generated dialplan.
CREATE TABLE IF NOT EXISTS ${q(schema)}.cdr (
  seq bigserial PRIMARY KEY,
  calldate timestamptz NOT NULL DEFAULT now(),
  answerdate timestamptz,
  enddate timestamptz,
  clid varchar(160), src varchar(80), dst varchar(80), dcontext varchar(80), channel varchar(160), dstchannel varchar(160),
  lastapp varchar(80), lastdata varchar(255), duration integer NOT NULL DEFAULT 0, billsec integer NOT NULL DEFAULT 0,
  disposition varchar(45) NOT NULL DEFAULT '', amaflags integer, accountcode varchar(80), uniqueid varchar(150) NOT NULL DEFAULT '',
  userfield varchar(255), peeraccount varchar(80), linkedid varchar(150) NOT NULL DEFAULT '', sequence integer,
  hangupcause integer,
  ech_pbx_id varchar(40), ech_trunk_id varchar(40), ech_route_id varchar(40), ech_route_pattern_id varchar(40),
  ech_server_id varchar(40), ech_direction varchar(16), ech_dialed varchar(80), ech_dialstatus varchar(20),
  ech_rec_file varchar(255), ech_rec_format varchar(10), ech_rec_policy varchar(64),
  sip_callid varchar(255), peer_ip varchar(80), user_agent varchar(255)
);
CREATE INDEX IF NOT EXISTS cdr_linkedid ON ${q(schema)}.cdr (linkedid);
CREATE INDEX IF NOT EXISTS cdr_calldate ON ${q(schema)}.cdr (calldate);

-- CEL (cel_odbc)
CREATE TABLE IF NOT EXISTS ${q(schema)}.cel (
  seq bigserial PRIMARY KEY,
  eventtype varchar(30) NOT NULL, eventtime timestamptz NOT NULL DEFAULT now(),
  cid_name varchar(80), cid_num varchar(80), cid_ani varchar(80), cid_rdnis varchar(80), cid_dnid varchar(80),
  exten varchar(80), context varchar(80), channame varchar(160), appname varchar(80), appdata varchar(512),
  amaflags integer, accountcode varchar(80), peeraccount varchar(80), uniqueid varchar(150), linkedid varchar(150),
  userfield varchar(255), peer varchar(160), userdeftype varchar(255), extra text
);
CREATE INDEX IF NOT EXISTS cel_linkedid ON ${q(schema)}.cel (linkedid);
`);

mkdirSync(path.join(here, '..', 'asterisk', 'sql'), { recursive: true });
const file = path.join(here, '..', 'asterisk', 'sql', schema === 'asterisk' ? 'asterisk_realtime.sql' : `asterisk_realtime_${schema}.sql`);
writeFileSync(file, out.join('\n'));
console.log(`wrote ${file}`);
